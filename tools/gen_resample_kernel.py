#!/usr/bin/env python3
"""The mixer's resampling kernel (src/mix/kernel.h): a low-pass at 20 kHz for input at the YM2612's
rate (53267 Hz), Kaiser window (beta 9), 32 taps, at 256 positions between two input samples. Each
row sums to exactly 32768. Integers, so the output is the same on every host."""
import math

TAPS, PHASES, BETA = 32, 256, 9.0
RATE = 53693175 / 1008
CUTOFF = 20000 / RATE                      # cycles per input sample


def i0(x):
    s, t, k = 1.0, 1.0, 1
    while t > 1e-12 * s:
        t *= (x / (2 * k)) ** 2
        s += t
        k += 1
    return s


print('/* generated by tools/gen_resample_kernel.py: 256 positions x 32 taps, a low-pass at 20 kHz */')
print('static const int16_t mix_kernel[%d][%d] = {' % (PHASES, TAPS))
for ph in range(PHASES):
    f = ph / PHASES
    row = []
    for j in range(TAPS):
        x = (j - 15) - f                       # tap j: the input sample j - 15 from the one before the output
        u = 2 * CUTOFF * x
        h = 2 * CUTOFF * (math.sin(math.pi * u) / (math.pi * u) if u else 1.0)
        r = x / 16.5
        w = i0(BETA * math.sqrt(1 - r * r)) / i0(BETA) if abs(r) < 1 else 0.0
        row.append(h * w)
    s = sum(row)
    ints = [round(v / s * 32768) for v in row]
    ints[max(range(TAPS), key=lambda k: ints[k])] += 32768 - sum(ints)
    print('    { ' + ', '.join(str(v) for v in ints) + ' },')
print('};')
