#!/usr/bin/env python3
"""The PSG's band-limited step kernel (src/psg/kernel.h): the impulse response of a low-pass at
0.40 of the output rate (21.3 kHz at 53267 Hz), Kaiser window (beta 8), 32 taps, for the 21
positions a transition can have inside an output sample (the PSG's internal clock is 240 master
clocks, a sample 1008: 21 positions 48 clocks apart). Each row is scaled to sum to exactly 32768,
so a step settles at its exact level. Integers, so the output is the same on every host."""
import math

TAPS, PHASES, CUTOFF, BETA = 32, 21, 0.40, 8.0


def i0(x):
    s, t, k = 1.0, 1.0, 1
    while t > 1e-12 * s:
        t *= (x / (2 * k)) ** 2
        s += t
        k += 1
    return s


rows = []
for ph in range(PHASES):
    f = ph / PHASES
    row = []
    for j in range(TAPS):
        x = (j - 15) - f                       # tap j: the sample j - 15 from the one the transition is in
        u = 2 * CUTOFF * x
        h = 2 * CUTOFF * (math.sin(math.pi * u) / (math.pi * u) if u else 1.0)
        r = x / 16.0
        w = i0(BETA * math.sqrt(1 - r * r)) / i0(BETA) if abs(r) < 1 else 0.0
        row.append(h * w)
    s = sum(row)
    ints = [round(v / s * 32768) for v in row]
    ints[max(range(TAPS), key=lambda k: ints[k])] += 32768 - sum(ints)
    rows.append(ints)

print('/* generated by tools/gen_psg_kernel.py: the band-limited step kernel, 21 positions x 32 taps */')
print('static const int16_t psg_kernel[%d][%d] = {' % (PHASES, TAPS))
for r in rows:
    print('    { ' + ', '.join(str(v) for v in r) + ' },')
print('};')
